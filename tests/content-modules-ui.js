const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { execFileSync } = require('node:child_process');
const { parseHTML } = require('linkedom');
const php = process.env.WUTM_TEST_PHP || 'php';
const fixture = (mode, view) => execFileSync(php, ['tests/content-modules.php', mode, ...(view ? [view] : [])], { encoding: 'utf8' });
const settle = () => new Promise(resolve => setTimeout(resolve, 20));
function contextFor(html, fetch) {
    const { document, window } = parseHTML(html);
    document.readyState = 'complete';
    window.matchMedia = () => ({ matches: true });
    window.scrollTo = () => {};
    window.HTMLElement.prototype.scrollIntoView = function () {};
    window.HTMLElement.prototype.focus = function () {};
    const context = { window, document, Event: window.Event, FormData, URLSearchParams, fetch, setTimeout, clearTimeout, console, ajaxurl: '/wp-admin/admin-ajax.php' };
    return { document, window, context };
}
async function main() {
    let requests = 0;
    const dashboard = fixture('dashboard');
    const { document, window, context } = contextFor(dashboard, async () => { requests++; throw new Error('Tabs must not fetch'); });
    for (const script of dashboard.matchAll(/<script>([\s\S]*?)<\/script>/g)) vm.runInNewContext(script[1], context);
    const tabs = [...document.querySelectorAll('.wutm-module-tab')];
    const cards = [...document.querySelectorAll('.wutm-card')];
    const actual = cards.filter(card => card.dataset.navigation !== '1');
    assert.equal(tabs.length, 3);
    assert.equal(tabs[0].getAttribute('aria-selected'), 'true', 'All modules selected initially');
    assert.equal(cards.filter(card => card.hidden).length, 0);
    assert.equal(Number(tabs[0].querySelector('.wutm-tab-count').textContent), actual.length);
    tabs[1].click();
    assert(cards.filter(card => !card.hidden).every(card => card.classList.contains('on')));
    assert.equal(document.querySelector('#wutm-module-panels').getAttribute('aria-labelledby'), 'wutm-tab-enabled');
    const enabled = actual.filter(card => card.classList.contains('on')).length;
    assert.equal(Number(tabs[1].querySelector('.wutm-tab-count').textContent), enabled);
    const keyboard = new window.Event('keydown', { bubbles: true, cancelable: true });
    keyboard.key = 'ArrowRight';
    tabs[1].dispatchEvent(keyboard);
    assert.equal(tabs[2].getAttribute('aria-selected'), 'true', 'Arrow keys select next filter');
    assert(cards.filter(card => !card.hidden).every(card => !card.classList.contains('on')));
    const card = document.getElementById('wutm-module-content-overview');
    card.classList.add('on');
    document.dispatchEvent(new window.Event('wutm-module-state-changed'));
    assert.equal(card.hidden, true, 'Successful module enable immediately updates current filter');
    assert.equal(Number(tabs[1].querySelector('.wutm-tab-count').textContent), enabled + 1);
    tabs[0].click();
    assert.equal(cards.filter(card => card.hidden).length, 0);
    document.getElementById('wutm-module-search-input').value = 'Google 地圖';
    document.querySelector('.wutm-module-search').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true }));
    assert.equal(document.querySelectorAll('.wutm-search-result').length, 1, 'Search remains functional with tabs');
    assert.equal(requests, 0, 'Filtering, keyboard, counts and search do not make network requests');
    const mapSource = fs.readFileSync('modules/google-maps/map-manager.php', 'utf8');
    for (const js of mapSource.matchAll(/<<<'JS'\r?\n([\s\S]*?)\r?\nJS;/g)) new vm.Script(js[1]);
    const data = Object.fromEntries(['pages', 'posts', 'products'].map(view => [view, JSON.parse(fixture('data', view))]));
    let calls = [], persist = [], htmlError = false, hold = false, release;
    const view = contextFor(fixture('overview'), async (url, options) => {
        const action = options.body.get('action');
        if (action === 'wco_v5_columns') {
            persist.push(options.body.getAll('columns[]'));
            return { ok: true, status: 200, text: async () => JSON.stringify({ success: true, data: {} }) };
        }
        const selected = options.body.get('view');
        calls.push(selected);
        if (hold) { hold = false; await new Promise(resolve => { release = resolve; }); }
        return { ok: !htmlError, status: htmlError ? 504 : 200, text: async () => htmlError ? '<!DOCTYPE html>server timeout' : JSON.stringify(data[selected]) };
    });
    for (const script of fixture('overview').matchAll(/<script>([\s\S]*?)<\/script>/g)) vm.runInNewContext(script[1], view.context);
    await settle();
    assert.deepEqual(calls, ['pages'], 'Initial load reads only pages');
    assert.equal(view.document.querySelectorAll('[data-view="pages"] .wco-tree-item').length, 5);
    view.document.querySelector('[data-tab="posts"]').click(); await settle();
    assert(view.document.querySelector('[data-view="pages"]').hidden);
    assert.equal(view.document.querySelectorAll('[data-view="posts"] .wco-tree-category').length, 2);
    view.document.querySelector('[data-tab="pages"]').click(); await settle();
    assert.deepEqual(calls, ['pages', 'posts'], 'Loaded tabs use cached data');
    view.document.querySelector('[data-tab="products"]').click(); await settle();
    assert.equal(view.document.querySelectorAll('[data-product-body] tr').length, 1);
    assert.equal(view.document.querySelector('[data-count]').textContent.includes('5'), true);
    const count = view.document.querySelector('[data-view="products"] [data-count]').textContent;
    assert(count.includes('21'));
    view.document.querySelector('[data-columns-button]').click();
    const column = view.document.querySelector('[data-column="thumb"]');
    column.checked = true;
    column.dispatchEvent(new view.window.Event('change', { bubbles: true }));
    await settle();
    assert(persist[0].includes('thumb') && persist[0].includes('name'), 'Per-user column settings save without losing required name');
    view.document.querySelector('[data-tab="pages"]').click();
    htmlError = true;
    view.document.querySelector('#wco-refresh').click(); await settle();
    assert(view.document.querySelector('[data-view="pages"] [data-message]').textContent.includes('HTTP 504'), 'Invalid JSON is shown as a real server error');
    assert.equal(view.document.querySelectorAll('[data-view="pages"] .wco-tree-item').length, 5, 'Failed refresh preserves displayed tree');
    htmlError = false;
    hold = true;
    const before = calls.length;
    view.document.querySelector('#wco-refresh').click();
    view.document.querySelector('#wco-refresh').click();
    assert.equal(calls.length, before + 1, 'Repeated refresh shares pending tree request');
    release(); await settle();
    const noWC = fixture('no-wc');
    assert(!noWC.includes('data-tab="products"'), 'No-WooCommerce sites retain pages/posts but not product tab');
    console.log('Content UI passed: accessible instant filters, search, cached tabs, product columns, errors, request deduplication and original block syntax.');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
